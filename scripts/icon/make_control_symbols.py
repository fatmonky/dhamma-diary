#!/usr/bin/env python3
"""Draws the one-colour custom symbols used by the Control Center controls
(spec 9.8) and writes them into the asset catalog as .symbolset folders.

Controls can only show a symbol, not the full-colour app icon, so:
- stone.book: a white stone above an open book, like the app icon (opens Today);
- mind.still / mind.between / mind.noisy: the stone with no specks, a few,
  and many, like the noise behind the stone on Today.

Run from the repo root:  python3 scripts/icon/make_control_symbols.py
Change this script, not the generated SVGs.
"""
import json
import os

ASSETS = "DhammaDiary/Assets.xcassets"

# SF Symbols template geometry: one master, Regular weight at Medium scale,
# which Xcode requires and uses for every weight and scale. The glyph is
# drawn in local units with the baseline at y=0 and the cap height at
# y=-70.459, x from 0 to `width`.
BASELINE_M = 1126
MASTERS = [("Regular-M", 1400)]


def circle(cx, cy, r):
    return (f"M{cx - r} {cy} A{r} {r} 0 1 0 {cx + r} {cy} "
            f"A{r} {r} 0 1 0 {cx - r} {cy} Z")


def rounded_bar(x0, x1, y0, y1):
    r = (y1 - y0) / 2
    return (f"M{x0 + r} {y0} L{x1 - r} {y0} A{r} {r} 0 0 1 {x1 - r} {y1} "
            f"L{x0 + r} {y1} A{r} {r} 0 0 1 {x0 + r} {y0} Z")


STONE = circle(40, -35, 22)

SYMBOLS = {
    "stone.book": (100, [
        circle(50, -50, 19),
        "M6 -26 Q28 -32 47 -22 L47 6 Q28 -4 6 2 Z",
        "M53 -22 Q72 -32 94 -26 L94 2 Q72 -4 53 6 Z",
    ]),
    "mind.still": (80, [
        STONE,
        rounded_bar(6, 74, -3, 3),
    ]),
    "mind.between": (84, [
        STONE,
        circle(8, -52, 4.5),
        circle(75, -58, 4.5),
        circle(70, -10, 4.5),
    ]),
    "mind.noisy": (84, [
        STONE,
        circle(6, -48, 4),
        circle(16, -67, 4),
        circle(62, -68, 4),
        circle(78, -50, 4),
        circle(78, -24, 4),
        circle(66, -2, 4),
        circle(14, -10, 4),
        circle(38, 2, 4),
    ]),
}


def svg(width, paths):
    guides = [
        f'<line id="Baseline-S" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="696" y2="696"/>',
        f'<line id="Capline-S" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="625.541" y2="625.541"/>',
        '<line id="Baseline-M" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="1126" y2="1126"/>',
        '<line id="Capline-M" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="1055.54" y2="1055.54"/>',
        '<line id="Baseline-L" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="1556" y2="1556"/>',
        '<line id="Capline-L" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="1485.54" y2="1485.54"/>',
    ]
    symbols = []
    for name, x in MASTERS:
        guides.append(f'<line id="left-margin-{name}" style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0;" x1="{x}" x2="{x}" y1="1030.79" y2="1150.12"/>')
        guides.append(f'<line id="right-margin-{name}" style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0;" x1="{x + width}" x2="{x + width}" y1="1030.79" y2="1150.12"/>')
        body = "\n   ".join(f'<path d="{d}"/>' for d in paths)
        symbols.append(f'  <g id="{name}" transform="matrix(1 0 0 1 {x} {BASELINE_M})">\n   {body}\n  </g>')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!-- Generated by scripts/icon/make_control_symbols.py. Edit the script, not this file. -->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" width="3300" height="2200">
 <g id="Notes">
  <rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>
 </g>
 <g id="Guides">
  {chr(10).join("  " + g for g in guides).strip()}
 </g>
 <g id="Symbols">
{chr(10).join(symbols)}
 </g>
</svg>
'''


def main():
    for name, (width, paths) in SYMBOLS.items():
        folder = os.path.join(ASSETS, f"{name}.symbolset")
        os.makedirs(folder, exist_ok=True)
        filename = f"{name}.svg"
        with open(os.path.join(folder, filename), "w") as f:
            f.write(svg(width, paths))
        with open(os.path.join(folder, "Contents.json"), "w") as f:
            json.dump({
                "info": {"author": "xcode", "version": 1},
                "symbols": [{"filename": filename, "idiom": "universal"}],
            }, f, indent=2)
            f.write("\n")
        print("wrote", folder)


if __name__ == "__main__":
    main()
